"""
Run this on your Windows machine inside the soteriaeyeclinic folder:
  python view_images.py

It scans frame_images/ and generates gallery.html which you can open in any browser.
"""
import os
import glob

IMAGE_DIR = "frame_images"
OUTPUT    = "gallery.html"

files = sorted(glob.glob(os.path.join(IMAGE_DIR, "MH-*.jpg")))
if not files:
    print("No images found in frame_images/  — run download_frame_images.py first.")
    exit()

cards = []
for path in files:
    name = os.path.basename(path)          # e.g. MH-460.jpg
    sku  = name.replace(".jpg", "")        # e.g. MH-460
    rel  = path.replace("\\", "/")        # forward slashes for HTML
    cards.append(f"""
      <div class="card">
        <img src="{rel}" alt="{sku}" loading="lazy">
        <p>{sku}</p>
      </div>""")

html = f"""<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
<title>M&amp;H Frame Images ({len(files)} downloaded)</title>
<style>
  body {{ font-family: Arial, sans-serif; background:#f4f4f4; margin:0; padding:16px; }}
  h1   {{ font-size:1.3rem; margin-bottom:4px; }}
  p.sub{{ color:#666; margin-top:0; font-size:.9rem; }}
  .grid{{
    display:grid;
    grid-template-columns: repeat(auto-fill, minmax(160px, 1fr));
    gap:12px;
    margin-top:16px;
  }}
  .card{{
    background:#fff;
    border-radius:8px;
    box-shadow:0 1px 4px rgba(0,0,0,.12);
    padding:8px;
    text-align:center;
  }}
  .card img{{
    width:100%;
    height:130px;
    object-fit:contain;
    border-radius:4px;
    background:#fafafa;
  }}
  .card p{{
    margin:6px 0 0;
    font-size:.78rem;
    font-weight:600;
    color:#333;
  }}
  input{{
    padding:8px 12px;
    width:280px;
    border:1px solid #ccc;
    border-radius:6px;
    font-size:.95rem;
  }}
</style>
</head>
<body>
<h1>M&amp;H Fashion — Downloaded Frame Images</h1>
<p class="sub">{len(files)} images in frame_images/ &nbsp;|&nbsp; Generated by view_images.py</p>

<input type="text" id="search" placeholder="Search by SKU e.g. MH-460" oninput="filter()">

<div class="grid" id="grid">{''.join(cards)}
</div>

<script>
function filter(){{
  var q = document.getElementById('search').value.toLowerCase();
  document.querySelectorAll('.card').forEach(function(c){{
    c.style.display = c.querySelector('p').textContent.toLowerCase().includes(q) ? '' : 'none';
  }});
}}
</script>
</body>
</html>"""

with open(OUTPUT, "w", encoding="utf-8") as f:
    f.write(html)

print(f"Done! Saved {OUTPUT} — open it in your browser to review all {len(files)} images.")
